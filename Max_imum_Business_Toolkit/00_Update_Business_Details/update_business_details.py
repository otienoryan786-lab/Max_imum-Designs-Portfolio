#!/usr/bin/env python3
"""Update Business Details tool for Max_imum Designs.

Fills your business details into every Word document (and the website config) in one go.
Your original documents are NEVER changed: filled copies go into the 'Filled_Documents' folder,
so you can run this again any time your details change.

How to use:  1) pip install python-docx     2) edit business-details.json
             3) python update_business_details.py
Extra folders (for example the brand package) can be added:  python update_business_details.py "C:/path/to/Max_imum_Designs_Brand_Package"
"""
import json, sys, shutil
from datetime import date
from pathlib import Path
try:
    import docx
except ImportError:
    sys.exit("Please install python-docx first:  pip install python-docx")

HERE = Path(__file__).resolve().parent
OUT = HERE / "Filled_Documents"
TOKENS = {  # json key -> token written in the documents
    "registered_business_name": "[REGISTERED BUSINESS NAME]",
    "business_registration_no": "[BUSINESS REGISTRATION NO.]",
    "kra_pin": "[KRA PIN]",
    "business_address": "[BUSINESS ADDRESS]",
    "mpesa_till_or_paybill": "[M-PESA TILL]",
    "odpc_statement": "[ODPC STATUS]",
    "last_updated": "[LAST UPDATED]",
}

def replace_in_paragraph(p, tok, val):
    """Replace tok with val even if Word has split the token across several runs."""
    while True:
        runs = p.runs
        full = "".join(r.text for r in runs)
        i = full.find(tok)
        if i < 0 or tok in val:
            return
        j, pos, first = i + len(tok), 0, True
        for r in runs:
            a, b = pos, pos + len(r.text)
            pos = b
            if b <= i or a >= j:
                continue
            s, e = max(i, a) - a, min(j, b) - a
            r.text = (r.text[:s] + val + r.text[e:]) if first else (r.text[:s] + r.text[e:])
            first = False

def all_paragraphs(d):
    def walk(container):
        for p in container.paragraphs:
            yield p
        for t in getattr(container, "tables", []):
            for row in t.rows:
                for c in row.cells:
                    yield from walk(c)
    yield from walk(d)
    for s in d.sections:
        for part in (s.header, s.footer, s.first_page_header, s.first_page_footer, s.even_page_header, s.even_page_footer):
            try:
                yield from walk(part)
            except Exception:
                pass

def main():
    cfg = json.loads((HERE / "business-details.json").read_text(encoding="utf-8"))
    d = date.today()
    if not cfg.get("last_updated", "").strip():
        cfg["last_updated"] = f"{d.day} {d:%B %Y}"
    values = {TOKENS[k]: str(cfg.get(k, "")).strip() for k in TOKENS}
    todo = [k for k, t in TOKENS.items() if not values[t]]
    roots = [HERE.parent] + [Path(a) for a in sys.argv[1:]]
    if OUT.exists():
        shutil.rmtree(OUT)
    n_files = n_repl = 0
    for root in roots:
        for f in sorted(root.rglob("*.docx")):
            if HERE in f.parents or OUT in f.parents or f.name.startswith("~$"):
                continue
            document = docx.Document(str(f))
            before = sum(p.text.count(t) for p in all_paragraphs(document) for t in values)
            for p in all_paragraphs(document):
                for tok, val in values.items():
                    if val:
                        replace_in_paragraph(p, tok, val)
            dest = OUT / root.name / f.relative_to(root)
            dest.parent.mkdir(parents=True, exist_ok=True)
            document.save(str(dest))
            after = sum(p.text.count(t) for p in all_paragraphs(docx.Document(str(dest))) for t in values)
            if before:
                n_files += 1; n_repl += before - after
    web = OUT / "Website_Upload" / "js"
    web.mkdir(parents=True, exist_ok=True)
    js = {"registered_name": cfg["registered_business_name"].strip(), "registration_no": cfg["business_registration_no"].strip(),
          "address": cfg["business_address"].strip(), "odpc_statement": cfg["odpc_statement"].strip(), "last_updated": cfg["last_updated"].strip()}
    lines = ",\n".join(f"  {k}: {json.dumps(v, ensure_ascii=False)}" for k, v in js.items())
    (web / "business-details.js").write_text("/* Generated by update_business_details.py. Upload this file to the js folder of your website repository. */\nwindow.BUSINESS = {\n" + lines + "\n};\n", encoding="utf-8")
    print(f"Done. {n_repl} details filled in {n_files} documents.")
    print(f"Filled documents: {OUT}")
    print(f"Website file to upload: {web / 'business-details.js'}  (into the js folder on GitHub)")
    if todo:
        print("Still empty (left as [TOKENS] in documents, hidden on the website): " + ", ".join(todo))

if __name__ == "__main__":
    main()
